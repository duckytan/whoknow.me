// homeSegment.ts
//
// 首页底部三段导航（外卖 / 首页 / 自取）的"切高亮"决策。
//
// 背景（防 D3 类塑料感；本轮补修前刚在这踩过一次）：
//   真美团里"自取"是独立频道，点了会切实切到自取列表。本产品"自取"是占位频道、
//   没有独立内容。如果照搬"点了就切高亮"，会出现"高亮停在自取 / 下面还是外卖内容"
//   的状态与内容打架画面——这正是 D3 那类"一眼看出是仿品"的毛病，只是换了个位置。
//   所以自取只弹提示、不切高亮：返回 null 即"调用方不要改 segActive"。
//
// 这是 D1/D2 同款的"外壳逻辑抽纯函数"做法：把'为什么自取不切高亮'的口径写进注释 +
// 单测钉死，避免下一轮又被改成切高亮（切了就等于把刚修好的塑料感搬回来）。

/**
 * 返回应该高亮的分段；返回 `null` 表示"不要切高亮"（如占位频道"自取"）。
 *
 * 调用方约定：仅当返回值非 null 时才写 `segActive`，从而
 * `nextHomeSeg('自取') === null` 即等价于"点自取后高亮保持原值"。
 */
export function nextHomeSeg(seg: string): string | null {
  if (seg === '自取') return null
  return seg
}
